import type { Book } from '@/lib/data';
import { UPSTREAM_TIMEOUT } from './http';
import type { SourceTier } from './resolveSource';

/**
 * Turns a catalogue Book into the record the public API returns: a legal
 * tier, a reason, a licence and the real files you can actually download.
 *
 * The rule this file exists to enforce: we never claim "free to download"
 * unless we have a file URL we can point at. A link to a search page is not a
 * download, and a record for a title we cannot confirm is not free.
 */

export type PublicFormat = 'epub' | 'pdf' | 'txt' | 'html' | 'zip' | 'mobi' | 'audio';

export interface PublicFile {
  format: PublicFormat;
  url: string;
  bytes: number | null;
  label: string;
}

export interface PublicRecord {
  id: string;
  title: string;
  author: string;
  year: number | null;
  source: string;
  sourceType: string;
  sourceUrl: string;
  tier: SourceTier;
  tierReason: string;
  license: string;
  files: PublicFile[];
  links: { label: string; url: string; source: string }[];
  /** The ANYFREEBOOK page for this title, when the slug maps to one. */
  url: string;
}

const SOURCE_LABELS: Record<string, string> = {
  local: 'ANYFREEBOOK',
  gutenberg: 'Project Gutenberg',
  openlibrary: 'Open Library',
  archive: 'Internet Archive',
  googlebooks: 'Google Books',
  pubmed: 'PubMed Central',
  doaj: 'DOAJ',
  librivox: 'LibriVox',
  openalex: 'OpenAlex',
  wikisource: 'Wikisource',
  europeana: 'Europeana',
  zenodo: 'Zenodo',
};

/** Formats we are willing to hand to a downloader, in the order we prefer them. */
const FORMAT_PRIORITY: PublicFormat[] = ['epub', 'pdf', 'txt', 'html', 'zip', 'mobi', 'audio'];

export function sourceLabel(sourceType: string | undefined): string {
  if (!sourceType) return 'ANYFREEBOOK';
  return SOURCE_LABELS[sourceType] || sourceType;
}

/* ------------------------------------------------------------------ *
 * Identifier extraction
 * ------------------------------------------------------------------ */

/** The Project Gutenberg ebook id, when this record is a Gutenberg title. */
export function gutenbergIdFor(book: Book): number | null {
  const fromId = /^pg-(\d+)$/.exec(book.id);
  if (fromId) return parseInt(fromId[1], 10);
  const fromSlug = /-pg-(\d+)$/.exec(book.slug);
  if (fromSlug) return parseInt(fromSlug[1], 10);
  return null;
}

/** The Internet Archive item identifier, when this record points at one. */
export function archiveIdentifierFor(book: Book): string | null {
  for (const link of book.downloadLinks || []) {
    const m = /archive\.org\/details\/([^/?#]+)/.exec(link.url);
    if (m) return decodeURIComponent(m[1]);
  }
  const fromId = /^ia-(.+)$/.exec(book.id);
  if (fromId) return fromId[1];
  const fromSlug = /-ia-(.+)$/.exec(book.slug);
  if (fromSlug) return fromSlug[1];
  return null;
}

/* ------------------------------------------------------------------ *
 * Project Gutenberg files
 * ------------------------------------------------------------------ */

/**
 * Gutenberg's canonical file URLs for an ebook id.
 *
 * These are stable and generated by Gutenberg itself. `.txt` and `.pdf` are
 * NOT reliable (the plain-text file is `.txt.utf-8`, and a PDF only exists for
 * some titles), so only the three that exist for every ebook are offered.
 */
export function gutenbergFiles(ebookId: number): PublicFile[] {
  const base = `https://www.gutenberg.org/ebooks/${ebookId}`;
  return [
    { format: 'epub', url: `${base}.epub3.images`, bytes: null, label: 'EPUB' },
    { format: 'txt', url: `${base}.txt.utf-8`, bytes: null, label: 'Plain text' },
    { format: 'html', url: `${base}.html.images`, bytes: null, label: 'HTML' },
  ];
}

/** Gutenberg links the source adapter already resolved (gutendex format map). */
function gutenbergFilesFromLinks(book: Book): PublicFile[] {
  const files: PublicFile[] = [];
  for (const link of book.downloadLinks || []) {
    const label = link.label.toLowerCase();
    if (!label.startsWith('download ')) continue;
    const name = link.label.replace(/^download\s+/i, '').trim().toLowerCase();
    const format: PublicFormat | null =
      name.includes('epub') ? 'epub'
      : name.includes('pdf') ? 'pdf'
      : name.includes('txt') ? 'txt'
      : name.includes('html') ? 'html'
      : null;
    if (!format) continue;
    files.push({ format, url: link.url, bytes: null, label: link.label.replace(/^download\s+/i, '') });
  }
  return files;
}

/* ------------------------------------------------------------------ *
 * Internet Archive files
 * ------------------------------------------------------------------ */

interface IaFile {
  name?: string;
  format?: string;
  size?: string;
  source?: string;
}

interface IaMetadata {
  metadata?: Record<string, string | string[]>;
  files?: IaFile[];
}

/**
 * Internet Archive file labels are exact strings, and several of them look
 * like a document format but are not one:
 *
 *   "OCR Search Text"  -> a gzipped search index, not the book
 *   "chOCR"            -> a gzipped OCR dump
 *   "Single Page Processed JP2 ZIP" -> 100+ MB of page images
 *   "Single Page Original JP2 Tar"  -> 700+ MB of page images
 *
 * So the label is matched exactly, and the file name is checked as well.
 */
const IA_FORMAT_MAP: { label: string; format: PublicFormat }[] = [
  { label: 'epub', format: 'epub' },
  { label: 'text pdf', format: 'pdf' },
  { label: 'pdf', format: 'pdf' },
  { label: 'djvutxt', format: 'txt' },
  { label: 'text', format: 'txt' },
  { label: 'hocr', format: 'html' },
  { label: 'html', format: 'html' },
  { label: 'single page html', format: 'html' },
];

/** File names that are never a readable document. */
const IA_REJECT_NAME = /\.(?:gz|tar|torrent|sqlite|xml|json|log|meta\.json)$|_jp2\.zip$|_orig_jp2\.tar$/i;

function iaFormatFor(formatLabel: string, name: string): PublicFormat | null {
  if (IA_REJECT_NAME.test(name)) return null;
  const label = (formatLabel || '').trim().toLowerCase();
  for (const entry of IA_FORMAT_MAP) {
    if (label === entry.label) return entry.format;
  }
  return null;
}

export interface IaItem {
  identifier: string;
  /** True when the item is borrow-only (Controlled Digital Lending). */
  restricted: boolean;
  rights: string | null;
  collection: string | null;
  files: PublicFile[];
}

/**
 * Asks Internet Archive's own metadata API about an item.
 *
 * The same call answers both questions we care about: is this copy open or
 * loan-only, and which files can actually be downloaded.
 */
export async function fetchArchiveItem(identifier: string): Promise<IaItem | null> {
  try {
    const res = await fetch(`https://archive.org/metadata/${encodeURIComponent(identifier)}`, {
      next: { revalidate: 86400 },
      signal: UPSTREAM_TIMEOUT(),
    });
    if (!res.ok) return null;
    const data = (await res.json()) as IaMetadata;
    const metadata = data.metadata || {};

    const restricted =
      metadata['access-restricted-item'] === 'true' ||
      !!metadata['lending_identifier'] ||
      !!metadata['lendinginfo'];

    const files: PublicFile[] = [];
    for (const file of data.files || []) {
      const name = file.name;
      if (!name || file.source === 'metadata') continue;
      // Skip the derivative noise (thumbnails, logs, metadata sidecars).
      if (/^(__ia_|.*\.(?:gif|jpg|jpeg|png|svg)$)/i.test(name)) continue;
      const format = iaFormatFor(file.format || '', name);
      if (!format) continue;
      files.push({
        format,
        url: `https://archive.org/download/${encodeURIComponent(identifier)}/${encodeURIComponent(name)}`,
        bytes: file.size ? parseInt(file.size, 10) || null : null,
        label: name,
      });
    }

    // Keep the best file per format.
    const best = new Map<PublicFormat, PublicFile>();
    for (const file of files) {
      const existing = best.get(file.format);
      if (!existing || (existing.bytes ?? Infinity) > (file.bytes ?? Infinity)) best.set(file.format, file);
    }
    const ordered = Array.from(best.values()).sort(
      (a, b) => FORMAT_PRIORITY.indexOf(a.format) - FORMAT_PRIORITY.indexOf(b.format)
    );

    const rights = typeof metadata['rights'] === 'string' ? metadata['rights'] : null;
    const collection = typeof metadata['collection'] === 'string' ? metadata['collection'] : null;

    return { identifier, restricted, rights, collection, files: ordered };
  } catch {
    return null;
  }
}

