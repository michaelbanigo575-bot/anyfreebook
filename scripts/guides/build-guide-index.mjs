#!/usr/bin/env node
/**
 * Build src/lib/guides.ts from the rendered guides.
 *
 * The PDF renderer writes, for each guide:
 *   public/guides/<slug>.pdf         the downloadable file
 *   public/guides/<slug>.body.html   the body, for the web page
 *
 * This script reads the spec and the body, and writes one TypeScript module
 * with everything the site needs: the metadata for the page, the keywords,
 * the section list for the contents, and the HTML for the body.
 *
 *   node scripts/guides/build-guide-index.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const SPEC_DIR = path.join(ROOT, 'content', 'guides');
const OUT_DIR = path.join(ROOT, 'public', 'guides');
const TARGET = path.join(ROOT, 'src', 'lib', 'guides.ts');

/** The order the guides appear in. */
const ORDER = [
  'back-to-school-encouragement-strategies',
  'first-30-days-university-starter-plan',
  'researchers-reentry-plan',
  'lecturer-reentry-plan',
  'free-study-resources-reading-plans',
];

const specs = fs
  .readdirSync(SPEC_DIR)
  .filter((f) => f.endsWith('.json') && f !== 'renderer-test.json')
  .map((f) => JSON.parse(fs.readFileSync(path.join(SPEC_DIR, f), 'utf8')));

specs.sort((a, b) => {
  const ai = ORDER.indexOf(a.slug);
  const bi = ORDER.indexOf(b.slug);
  if (ai !== -1 && bi !== -1) return ai - bi;
  if (ai !== -1) return -1;
  if (bi !== -1) return 1;
  return a.title.localeCompare(b.title);
});

const entries = [];

for (const spec of specs) {
  const bodyPath = path.join(OUT_DIR, `${spec.slug}.body.html`);
  const pdfPath = path.join(OUT_DIR, `${spec.slug}.pdf`);
  if (!fs.existsSync(bodyPath) || !fs.existsSync(pdfPath)) {
    console.log(`skipping ${spec.slug}: render it first`);
    continue;
  }

  const bodyHtml = fs.readFileSync(bodyPath, 'utf8');
  const sections = [...spec.body_md.matchAll(/^##\s+(.+)$/gm)].map((m) => {
    const title = m[1].trim();
    const anchor = title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');
    return { title, anchor };
  });

  entries.push({
    slug: spec.slug,
    title: spec.title,
    subtitle: spec.subtitle,
    audience: spec.audience,
    description: spec.description,
    about: spec.about,
    keywords: spec.keywords,
    accent: spec.accent,
    date: spec.date,
    sections,
    bodyHtml,
  });
}

if (entries.length === 0) {
  console.error('No rendered guides found.');
  process.exit(1);
}

const js = `/**
 * The ANYFREEBOOK guides.
 *
 * Generated by scripts/guides/build-guide-index.mjs from the files in
 * content/guides and the rendered bodies in public/guides. Do not edit this
 * file by hand: edit the spec, re-render the PDF, and run the script again.
 *
 * Each guide is a 20-plus page PDF, free to download, and the same text is
 * on this page so it can be read without the file.
 */

export interface GuideSection {
  title: string;
  anchor: string;
}

export interface Guide {
  slug: string;
  title: string;
  subtitle: string;
  audience: string;
  description: string;
  about: string;
  keywords: string[];
  accent: string;
  date: string;
  sections: GuideSection[];
  /** The body of the guide, as HTML. */
  bodyHtml: string;
}

export const GUIDES: Guide[] = ${JSON.stringify(entries, null, 2)};

export function getGuide(slug: string): Guide | undefined {
  return GUIDES.find((g) => g.slug === slug);
}
`;

fs.writeFileSync(TARGET, js, 'utf8');
console.log(`Wrote ${TARGET} with ${entries.length} guides:`);
for (const entry of entries) {
  console.log(`  ${entry.slug} — ${entry.title}`);
}
